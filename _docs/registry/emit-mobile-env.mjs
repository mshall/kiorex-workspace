#!/usr/bin/env node
// Generates the build-time environment profile of a MOBILE app from the URL registry (ADR-059). Nobody types a host into the apps.
//
//   node _docs/registry/emit-mobile-env.mjs --app kiorex|kiorly --env local|test|pilot|prod [--out <file>]
//   node _docs/registry/emit-mobile-env.mjs --write-all        rewrites <app>/config/env/<env>.env of both apps (the committed profile files)
//   node _docs/registry/emit-mobile-env.mjs --check            exits 1 when a committed profile file differs from what the registry produces
//
// Output is a plain KEY=value file: public client configuration only, no secret, no credential. `local` is the only profile that is not
// registry-derived (localhost development ports of the workspace, INTEGRATION.md); `local-android` points at the Android emulator's host alias.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { hostOf, issuerFor, load } from "./validate-registry.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const ws = path.resolve(here, "../..");
const APP_DIRS = { kiorex: "kiorex-platform/apps/mobile", kiorly: "kiorly" };
const ENVS = ["local", "local-android", "test", "pilot", "prod"];
const arg = (n) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? process.argv[i + 1] : undefined; };

const LOCAL = {
  kiorex: { EXPO_PUBLIC_API_URL: "http://localhost:4000/api/v1", EXPO_PUBLIC_OIDC_ISSUER: "http://localhost:4400", EXPO_PUBLIC_OIDC_CLIENT_ID: "kiorex-mobile" },
  kiorly: { EXPO_PUBLIC_CLINIC_API: "http://localhost:3010/api/v1", EXPO_PUBLIC_PHARMACY_API: "http://localhost:3100/api/v1", EXPO_PUBLIC_LAB_API: "http://localhost:3200/api/v1", EXPO_PUBLIC_PASSPORT_ISSUER: "http://localhost:4400", EXPO_PUBLIC_PASSPORT_CLIENT_ID: "kiorly" },
};

export function profile(reg, app, env) {
  const h = (service, e = env) => { const v = hostOf(reg, service, e); if (!v) throw new Error(`registry has no host for ${service} in ${e}`); return `https://${v}`; };
  if (env === "local" || env === "local-android") {
    const v = { APP_ENV: "development", EXPO_PUBLIC_ENV: "development", ...LOCAL[app] };
    if (env === "local-android") for (const k of Object.keys(v)) v[k] = v[k].replace("//localhost", "//10.0.2.2");
    return v;
  }
  if (!reg.environments.some((e) => e.id === env)) throw new Error(`unknown environment ${env}`);
  const issuer = issuerFor(reg, env);
  const common = { APP_ENV: env === "test" ? "preview" : env === "pilot" ? "pilot" : "production", EXPO_PUBLIC_ENV: env === "prod" ? "production" : env };
  if (app === "kiorex") {
    const linkHost = hostOf(reg, reg.app_links.patient_app_host_service, env);
    return { ...common, EXPO_PUBLIC_API_URL: `${h("kiorex.api")}/api/v1`, EXPO_PUBLIC_OIDC_ISSUER: issuer, EXPO_PUBLIC_OIDC_CLIENT_ID: "kiorex-mobile", APP_LINK_HOST: linkHost, EXPO_PUBLIC_LINK_HOSTS: linkHost };
  }
  const linkHost = hostOf(reg, reg.app_links.staff_app_host_service, env);
  return {
    ...common, EXPO_PUBLIC_CLINIC_API: `${h("kiorly.clinics")}/api/v1`, EXPO_PUBLIC_PHARMACY_API: `${h("kiorly.pharmacies")}/api/v1`, EXPO_PUBLIC_LAB_API: `${h("kiorly.labs")}/api/v1`,
    EXPO_PUBLIC_PASSPORT_ISSUER: issuer, EXPO_PUBLIC_PASSPORT_CLIENT_ID: "kiorly", STAFF_LINK_HOST: linkHost,
  };
}

export function render(app, env, vars) {
  const head = `# ${app} mobile build profile "${env}". GENERATED by _docs/registry/emit-mobile-env.mjs from the URL registry (ADR-059): do not edit by hand.\n# Public client configuration only (hosts, public client id). No secret, no credential, no store or EAS identifier.\n`;
  return head + Object.entries(vars).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const reg = load();
  const files = [];
  for (const [app, dir] of Object.entries(APP_DIRS)) for (const env of ENVS) files.push({ app, env, file: path.join(ws, dir, "config/env", `${env}.env`), text: render(app, env, profile(reg, app, env)) });
  if (process.argv.includes("--write-all")) {
    for (const f of files) { mkdirSync(path.dirname(f.file), { recursive: true }); writeFileSync(f.file, f.text); console.log(`wrote ${path.relative(ws, f.file)}`); }
  } else if (process.argv.includes("--check")) {
    const bad = files.filter((f) => !existsSync(f.file) || readFileSync(f.file, "utf8") !== f.text);
    if (bad.length) { console.error(`stale mobile profile(s), run --write-all: ${bad.map((f) => path.relative(ws, f.file)).join(", ")}`); process.exit(1); }
    console.log(`mobile profiles OK (${files.length})`);
  } else {
    const app = arg("app"), env = arg("env");
    if (!APP_DIRS[app] || !ENVS.includes(env)) { console.error("usage: --app kiorex|kiorly --env local|local-android|test|pilot|prod [--out file] | --write-all | --check"); process.exit(64); }
    const text = render(app, env, profile(reg, app, env));
    if (arg("out")) writeFileSync(arg("out"), text); else process.stdout.write(text);
  }
}
