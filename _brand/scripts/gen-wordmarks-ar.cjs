// Shapes the Arabic lockup words with HarfBuzz (harfbuzzjs: full GSUB/GPOS Arabic shaping + joining) from IBM Plex Sans Arabic (OFL-1.1)
// and writes outlined glyph paths to components/shared/wordmarks-ar.generated.ts. opentype.js alone does NOT shape Arabic.
// Colour changes mid-word (the ي of كيورلي) are done per shaped glyph, so letter joining is never broken.
// Coordinates: baseline y=0 (y grows downward, ink above the baseline is negative), x starts at 0 (ink left); em size is EM units per em.
