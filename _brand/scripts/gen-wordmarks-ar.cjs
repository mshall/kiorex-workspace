const num = (n) => +n.toFixed(2);
// glyphToPath gives absolute M/L/Q/C/Z in font units (y-up); we flip to y-down; convert to lockup units, y down, with an x offset.
function xform(d, s, dx) {
  const t = d.match(/[MLQCZ]|-?\d*\.?\d+(?:e-?\d+)?/gi) || [];
  let out = "", i = 0, cmd = "";
  while (i < t.length) {
    if (/[A-Za-z]/.test(t[i])) { cmd = t[i++]; out += cmd; if (cmd === "Z") continue; }
    const n = cmd === "Q" ? 4 : cmd === "C" ? 6 : 2;
    const pts = [];
    for (let k = 0; k < n; k += 2) pts.push(`${num(parseFloat(t[i + k]) * s + dx)} ${num(-parseFloat(t[i + k + 1]) * s)}`);
    out += pts.join(" "); i += n;
  }
  return out;
}

(async () => {
  const hb = await import(pathToFileURL(resolveEsm("harfbuzzjs")).href);
  const fonts = {};
  const getFont = (w) => fonts[w] || (fonts[w] = (() => { const blob = new hb.Blob(fs.readFileSync(FONT(w))); const face = new hb.Face(blob); return { font: new hb.Font(face), upem: face.upem }; })());

  /** accentFrom: index (UTF-16) of the first char painted in the accent role; -1 = none. */
  function word(text, weight, em, accentFrom, features = []) {
    const { font, upem } = getFont(weight);
    const buf = new hb.Buffer();
    buf.addText(text); buf.guessSegmentProperties();
    hb.shape(font, buf, features);
    const infos = buf.getGlyphInfos(), pos = buf.getGlyphPositions();
    const s = em / upem;
    let x = 0; const raw = []; if (process.env.DBG) console.log(text, JSON.stringify(pos), s);
    infos.forEach((g, i) => {
      const d = font.glyphToPath(g.codepoint);
      raw.push({ d, x: x + pos[i].xOffset * s, role: accentFrom >= 0 && g.cluster >= accentFrom ? "secondary" : "primary", cl: g.cluster });
      x += pos[i].xAdvance * s;
    });
    // ink bounds
    let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
    const live = raw.filter((r) => r.d);
    live.forEach((r) => (xform(r.d, s, r.x).match(/-?\d+\.?\d*/g) || []).forEach((v, k) => { const f = parseFloat(v); if (k % 2 === 0) { minX = Math.min(minX, f); maxX = Math.max(maxX, f); } else { minY = Math.min(minY, f); maxY = Math.max(maxY, f); } }));
    const out = live.map((r) => ({ d: xform(r.d, s, r.x - minX), role: r.role })); // shift so ink-left = 0
    return { letters: out.map((l) => ({ d: l.d, role: l.role })), width: num(maxX - minX), top: num(minY), bottom: num(maxY) };
  }
  const words = {
    KIORLY: word("كيورلي", 500, EM, 5, [new hb.Feature("rlig", 0, 4, 6)]),          // ك ي و ر ل = indigo, final ي = product accent
    CLINIC: word("للعيادات", 600, EM, 0),
    LAB: word("لاب", 600, EM, 0),
    PHARMACY: word("للصيدليات", 600, EM, 0),
    BY_KIOREX: word("من كيوريكس", 600, EM, -1),
  };
  fs.writeFileSync(path.join(__dirname, "../components/shared/wordmarks-ar.generated.ts"), `// GENERATED by scripts/gen-wordmarks-ar.cjs: Arabic words shaped with HarfBuzz from IBM Plex Sans Arabic (OFL-1.1), outlined (no font needed at runtime). Do not edit.
// Coordinates: baseline y=0 (y down), em size ${EM}, ink-left x=0. KIORLY: the final ي is role "secondary"; product words are all "secondary" (drawn in the product accent).
export type ArWordLetter = { d: string; role: "primary" | "secondary" };
export type ArWord = { letters: ArWordLetter[]; width: number; top: number; bottom: number };
export const WORDS_AR: Record<"KIORLY" | "CLINIC" | "LAB" | "PHARMACY" | "BY_KIOREX", ArWord> = ${JSON.stringify(words)};
`);
  console.log(Object.fromEntries(Object.entries(words).map(([k, v]) => [k, [v.width, v.top, v.bottom, v.letters.length]])));
})();
