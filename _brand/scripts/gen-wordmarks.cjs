// Outlines wordmarks from Jost Medium with opentype.js, using the founder KIOREX tracking, into components/shared/wordmarks.generated.ts
// Approach: cap height = 135 units, baseline y=0, x starts at 0. Pair spacing is fitted to founder artwork (K..X left edges in kiorex-wordmark.svg).
const fs = require("fs"), path = require("path");
const need = require("./resolve.cjs");
const opentype = need("opentype.js");
const f = opentype.loadSync(need.JOST);
const em = f.unitsPerEm, cap = f.tables.os2.sCapHeight || 700, CAP = 135, size = (CAP / cap) * em, sc = size / em;
const founder = { K: 98, I: 275, O: 380, R: 598, E: 770, X: 926 };
const order = ["K", "I", "O", "R", "E", "X"];
const inkLeft = (ch) => f.charToGlyph(ch).getBoundingBox().x1 * sc;
const adv = (ch) => f.charToGlyph(ch).advanceWidth * sc;
let tr = [];
for (let i = 0; i < 5; i++) {
  const a = order[i], b = order[i + 1];
  tr.push((founder[b] - inkLeft(b)) - (founder[a] - inkLeft(a)) - adv(a));
}
const TRACK = tr.reduce((a, b) => a + b, 0) / tr.length;
function word(text, track = TRACK, lastRole = "secondary") {
  const chars = [...text]; const bbL = inkLeft(chars[0]);
  let x = -bbL; const letters = [];
  chars.forEach((ch, i) => {
    if (ch !== " ") letters.push({ d: f.charToGlyph(ch).getPath(x, 0, size).toPathData(2), role: i === chars.length - 1 && lastRole ? lastRole : "primary" });
    x += adv(ch) + track;
  });
  const last = chars[chars.length - 1];
  const width = x - track - adv(last) + f.charToGlyph(last).getBoundingBox().x2 * sc;
  return { letters, width: +width.toFixed(2) };
}
const words = {
  KIOREX: word("KIOREX"), KIORLY: word("KIORLY"),
  BY_KIOREX: word("BY KIOREX", TRACK * 1.6, null), PASSPORT: word("PASSPORT", TRACK * 1.6, null), NURSE: word("NURSE", TRACK * 1.6, null),
};
fs.writeFileSync(path.join(__dirname, "../components/shared/wordmarks.generated.ts"), `// GENERATED by scripts/gen-wordmarks.cjs from Jost Medium (outlined; no font needed at runtime). Do not edit.
// Coordinates: cap height 135, baseline y=0, ink starts at x=0.
export type WordLetter = { d: string; role: "primary" | "secondary" };
export type Word = { letters: WordLetter[]; width: number };
export const CAP_HEIGHT = ${CAP};
export const WORDS: Record<"KIOREX" | "KIORLY" | "BY_KIOREX" | "PASSPORT" | "NURSE", Word> = ${JSON.stringify(words)};
`);
console.log("tracking", TRACK.toFixed(2), Object.fromEntries(Object.entries(words).map(([k, v]) => [k, v.width])));
